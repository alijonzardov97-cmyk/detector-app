package com.alijon.detector

import android.os.SystemClock
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue

/* ===========================================================================
 *  Проводка: отсчёты и поиск целей
 * ===========================================================================
 *
 *  ЗАЧЕМ ЭТО ПОЯВИЛОСЬ.
 *
 *  Задача — увидеть, что под катушкой не один предмет, а два, лежащих в
 *  десятке сантиметров друг от друга. При проводке метр в секунду это два
 *  всплеска с промежутком около сотни миллисекунд.
 *
 *  Отсчёты копятся ПО ПРИХОДУ строк. Прибор шлёт строку при каждом изменении
 *  ступени, не чаще раза в 15 мс, и с собственной меткой времени — поэтому
 *  моменты переходов известны с разрешением 15..25 мс, без дрожи эфира.
 *
 *  ЧЕГО ЭТО НЕ МОЖЕТ. Провал должен быть в самом сигнале. Восемь компараторных
 *  порогов — сетка грубая: если между целями отклик просел, но не пересёк ни
 *  одного порога, для прибора провала не было, и достать его неоткуда.
 *
 *  --- ЧТО ЗДЕСЬ БЫЛО И ОТКАЧЕНО ---------------------------------------------
 *
 *  В версии 2.6 поиск был переделан: вершины искались по одному разу
 *  нарастающим итогом, а дрожание снималось гистерезисом до поиска. На
 *  синтетических проводках это давало лучший счёт при любой настройке. На
 *  живом приборе стало хуже, и версия откачена к этой.
 *
 *  Вывод на будущее: синтетические профили здесь — мои догадки о форме
 *  сигнала, а не сам сигнал. Проверять такие вещи можно только записью с
 *  живого прибора. И отдельно: гистерезис сглаживал ещё и ТЕ отсчёты, что
 *  уходят на поле точек, — то есть подменял человеку картинку, по которой он
 *  судит о приборе. Так делать нельзя в любом случае: фильтровать можно то,
 *  по чему считаем, но не то, что показываем.
 */

/** Один отсчёт: когда пришёл и какая была ступень. */
data class Sample(val t: Long, val level: Int)

/**
 * Скользящее окно отсчётов и найденные в нём цели.
 *
 * Пополняется из потока Bluetooth, читается с главного потока при отрисовке.
 * Списки заменяются целиком, а не правятся на месте: тот экземпляр, который
 * начал рисовать холст, уже никогда не изменится, и гонки не возникает.
 */
class SweepBuffer {

    /*
     * Длина окна — одно число на всё.
     *
     * По нему живёт и картинка, и счётчик: сколько времени видно на поле,
     * столько же участвует в подсчёте. Ставится из настройки «Размах».
     */
    var windowMs: Long = WINDOW_FAST
        set(v) { field = v.coerceIn(500L, 6000L) }

    /*
     * Отсчёты и вершины — обычные поля, а не состояние Compose.
     *
     * Иначе каждая пришедшая строка (до шестидесяти в секунду) перерисовывала
     * бы поле целиком: до двух сотен кружков с прозрачностью плюс ореолы плюс
     * подписи осей. Холст подписан на tick, который растёт не чаще REDRAW_MS,
     * а данные читает уже отсюда. На сам счёт это не влияет никак — только на
     * частоту кадров.
     */
    @Volatile var samples: List<Sample> = emptyList()
        private set

    @Volatile var peaks: List<Sample> = emptyList()
        private set

    /** Счётчик кадров: холст подписан на него, растёт не чаще REDRAW_MS. */
    var tick by mutableStateOf(0)
        private set

    /**
     * Сколько целей в окне. Отдельное состояние: его читает подпись на экране,
     * а меняется оно редко — только когда цель появилась или ушла из окна.
     */
    var count by mutableStateOf(0)
        private set

    /**
     * На сколько ступеней должен просесть сигнал между целями, чтобы считать
     * их разными. Ставится из настроек: грубее сетка — больше значение.
     */
    var dip: Int = DIP_DEFAULT

    /** Часы прибора идут своим ходом; на их скачок назад окно сбрасываем. */
    private var lastDeviceMs = Long.MIN_VALUE
    private var lastTickMs = 0L

    /**
     * @param level     ступень из телеметрии
     * @param deviceMs  собственное время прибора; null — прошивка старая,
     *                  тогда время ставит телефон.
     *
     * Время прибора предпочтительнее нарочно. Метка телефона ставится в момент
     * прихода строки, а туда входит интервал соединения Bluetooth — те же
     * 15..30 мс, что мы и пытаемся измерить, да ещё и плавающие.
     */
    fun add(level: Int, deviceMs: Long? = null) {
        val now: Long
        if (deviceMs != null) {
            // millis() на приборе переполняется раз в 49 суток. Прыжок назад
            // означает именно это, и старое окно после него бессмысленно.
            if (deviceMs < lastDeviceMs) clear()
            lastDeviceMs = deviceMs
            now = deviceMs
        } else {
            now = SystemClock.elapsedRealtime()
        }

        val cut = now - windowMs
        var head = 0
        while (head < samples.size && samples[head].t < cut) head++
        val next = ArrayList<Sample>(samples.size - head + 1)
        for (i in head until samples.size) next.add(samples[i])
        next.add(Sample(now, level))
        samples = next

        val found = findPeaks(next, dip, MIN_TOP_SAMPLES, MIN_GAP_MS)
        peaks = found
        if (found.size != count) count = found.size
        if (now - lastTickMs >= REDRAW_MS) { lastTickMs = now; tick++ }
    }

    /** Связь оборвалась или прибор сменили — старое окно больше не про него. */
    fun clear() {
        samples = emptyList()
        peaks = emptyList()
        count = 0
        lastDeviceMs = Long.MIN_VALUE
        tick++
    }

    companion object {
        /*
         * Три размаха.
         *
         * Короткое окно лечит самую частую ошибку счёта: при взмахе
         * туда-обратно над ОДНИМ предметом получаются две вершины, и в длинном
         * окне обе попадают в счёт. Обратный взмах в секунду не влезает.
         *
         * Длинное окно, наоборот, нужно при неспешной проводке: две цели,
         * разнесённые на пару секунд, иначе не встретятся в одном окне.
         */
        const val WINDOW_FAST = 1000L        // TUNE
        const val WINDOW_MID  = 1500L        // TUNE
        const val WINDOW_SLOW = 2500L        // TUNE

        /** 0 — быстро, 1 — средне, 2 — медленно. Так хранится настройка. */
        fun windowFor(speed: Int): Long = when (speed) {
            2 -> WINDOW_SLOW
            1 -> WINDOW_MID
            else -> WINDOW_FAST
        }

        const val DIP_DEFAULT = 2            // TUNE: провал между целями, ступеней
        private const val CAP = 400

        /** Сколько отсчётов должно продержаться у вершины, чтобы её засчитать. */
        const val MIN_TOP_SAMPLES = 2        // TUNE
        /** Ближе этого две вершины считаются одной. */
        const val MIN_GAP_MS = 60L           // TUNE

        /** Не чаще этого перерисовывается поле. 33 мс — тридцать кадров в секунду. */
        const val REDRAW_MS = 33L            // TUNE

        /**
         * Вершины в последовательности ступеней.
         *
         * Запоминаем самую высокую точку, и как только сигнал от неё просел на
         * dip ступеней — вершина состоялась. Незакрытую вершину не засчитываем:
         * пока цель ещё под катушкой, счётчик иначе дёргался бы на каждом
         * отсчёте.
         *
         * Время вершины — СЕРЕДИНА ПЛАТО. Ступеней всего восемь, на макушке
         * сигнал стоит плато из нескольких отсчётов, и брать первый из них
         * значит сдвигать цель назад по времени на всю ширину плато.
         *
         * Промежуток меряется от последней записанной вершины В САМОМ СПИСКЕ.
         * Отдельная переменная с начальным Long.MIN_VALUE давала переполнение
         * при вычитании, проверка не проходила никогда, и счётчик стоял на нуле.
         */
        fun findPeaks(s: List<Sample>, dip: Int, minTop: Int, minGapMs: Long): List<Sample> {
            if (s.size < 3) return emptyList()
            val need = maxOf(2, dip)
            val out = ArrayList<Sample>(4)

            var best = -1          // ступень кандидата
            var from = 0L          // начало плато
            var to = 0L            // конец плато
            var top = 0            // отсчётов вблизи вершины

            for (x in s) {
                if (best < 0 || x.level > best) {
                    best = x.level; from = x.t; to = x.t; top = 1
                    continue
                }
                if (x.level == best) { to = x.t; top++; continue }

                // Про dip спрашиваем ПЕРВЫМ: иначе при dip = 1 ветка «в пределах
                // одной ступени» забирала себе тот отсчёт, который должен был
                // вершину закрыть, и на единице не находилось ничего.
                if (best - x.level < dip) {
                    if (x.level >= best - 1) top++
                    continue
                }

                val mid = from + (to - from) / 2
                if (best >= need && top >= minTop &&
                    (out.isEmpty() || mid - out.last().t >= minGapMs)
                ) {
                    out += Sample(mid, best)
                }
                best = -1; top = 0
            }
            return out
        }
    }
}
