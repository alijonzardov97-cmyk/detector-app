package com.alijon.detector

import android.os.SystemClock
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue

/* ===========================================================================
 *  Проводка: отсчёты и поиск целей
 * ===========================================================================
 *
 *  ЗАЧЕМ ЭТО ПОЯВИЛОСЬ.
 *
 *  Задача — увидеть, что под катушкой не один предмет, а два, лежащих в
 *  десятке сантиметров друг от друга. При проводке метр в секунду это два
 *  всплеска с промежутком около сотни миллисекунд.
 *
 *  Раньше график брал отсчёт по таймеру раз в 50 мс. На промежуток в 100 мс
 *  приходилось две точки, и провал между целями попросту проваливался между
 *  отсчётами — две цели сливались в один горб не потому, что прибор их не
 *  разделил, а потому, что график их усреднил.
 *
 *  Здесь отсчёты копятся ПО ПРИХОДУ строк. Прибор шлёт строку при каждом
 *  изменении ступени, не чаще раза в 15 мс, поэтому моменты переходов
 *  сохраняются с разрешением 15..25 мс — вчетверо точнее прежнего, и без
 *  единой правки в приборе.
 *
 *  ЧЕГО ЭТО НЕ МОЖЕТ. Провал должен быть в самом сигнале. Восемь компараторных
 *  порогов — сетка грубая: если между целями отклик просел, но не пересёк ни
 *  одного порога, для прибора провала не было, и достать его неоткуда.
 */

/** Один отсчёт: когда пришёл и какая была ступень. */
data class Sample(val t: Long, val level: Int)

/**
 * Скользящее окно отсчётов и найденные в нём цели.
 *
 * Состояние Compose, но читать его надо ВНУТРИ Canvas — в блоке отрисовки.
 * Тогда приход каждой строки вызывает только перерисовку холста, а не
 * рекомпозицию всего экрана прибора. При тридцати-шестидесяти строках в
 * секунду разница принципиальная.
 *
 * Пополняется из потока Bluetooth. Пишущий поток один, поэтому чтение-запись
 * списка гонки не даёт.
 */
class SweepBuffer {

    /*
     * Длина окна — одно число на всё.
     *
     * По нему живёт и картинка, и счётчик: сколько времени видно на поле,
     * столько же участвует в подсчёте. Разводить их нельзя — иначе поле
     * показывало бы две цели, а счётчик единицу, и разбираться было бы негде.
     * Ставится из настройки «Размах».
     */
    var windowMs: Long = WINDOW_FAST
        set(v) { field = v.coerceIn(500L, 6000L) }

    /** Отсчёты за последние windowMs. Читать в блоке отрисовки. */
    var samples by mutableStateOf<List<Sample>>(emptyList())
        private set

    /** Найденные вершины. Читать в блоке отрисовки. */
    var peaks by mutableStateOf<List<Sample>>(emptyList())
        private set

    /**
     * Сколько целей в окне. Отдельно от peaks нарочно: это значение читает
     * подпись на экране, то есть рекомпозиция. Меняется оно редко — только
     * когда цель появилась или ушла из окна.
     */
    var count by mutableStateOf(0)
        private set

    /**
     * На сколько ступеней должен просесть сигнал между целями, чтобы считать
     * их разными. Ставится из настроек: грубее сетка — больше значение.
     */
    var dip: Int = DIP_DEFAULT

    /** Часы прибора идут своим ходом; на их скачок назад окно сбрасываем. */
    private var lastDeviceMs = Long.MIN_VALUE

    /**
     * @param level     ступень из телеметрии
     * @param deviceMs  собственное время прибора; null — прошивка старая,
     *                  тогда время ставит телефон.
     *
     * Время прибора предпочтительнее нарочно. Метка телефона ставится в момент
     * прихода строки, а туда входит интервал соединения Bluetooth — те же
     * 15..30 мс, что мы и пытаемся измерить, да ещё и плавающие. Промежуток
     * между двумя целями измерялся с ошибкой порядка самого промежутка.
     */
    fun add(level: Int, deviceMs: Long? = null) {
        val now: Long
        if (deviceMs != null) {
            // millis() на приборе переполняется раз в 49 суток. Прыжок назад
            // означает именно это, и старое окно после него бессмысленно.
            if (deviceMs < lastDeviceMs) clear()
            lastDeviceMs = deviceMs
            now = deviceMs
        } else {
            now = SystemClock.elapsedRealtime()
        }
        val cut = now - windowMs
        // takeLast — страховка от разрастания, если часы вдруг поведут себя
        // неожиданно: окно всё равно не может содержать столько отсчётов.
        val next = (samples.filter { it.t >= cut } + Sample(now, level)).takeLast(CAP)
        samples = next

        val found = findPeaks(next, dip, MIN_TOP_SAMPLES, MIN_GAP_MS)
        peaks = found
        if (found.size != count) count = found.size
    }

    /** Связь оборвалась или прибор сменили — старое окно больше не про него. */
    fun clear() {
        samples = emptyList()
        peaks = emptyList()
        count = 0
        lastDeviceMs = Long.MIN_VALUE
    }

    companion object {
        /*
         * Три размаха.
         *
         * Короткое окно лечит самую частую ошибку счёта: при взмахе
         * туда-обратно над ОДНИМ предметом получаются две вершины, и в длинном
         * окне обе попадают в счёт. Обратный взмах в секунду просто не влезает.
         *
         * Длинное окно, наоборот, нужно при неспешной проводке: две цели,
         * разнесённые на пару секунд, иначе не встретятся в одном окне и
         * будут посчитаны порознь.
         */
        const val WINDOW_FAST = 1000L        // TUNE
        const val WINDOW_MID  = 1500L        // TUNE
        const val WINDOW_SLOW = 2500L        // TUNE

        /** 0 — быстро, 1 — средне, 2 — медленно. Так хранится настройка. */
        fun windowFor(speed: Int): Long = when (speed) {
            2 -> WINDOW_SLOW
            1 -> WINDOW_MID
            else -> WINDOW_FAST
        }

        const val DIP_DEFAULT = 2            // TUNE: провал между целями, ступеней
        private const val CAP = 400

        /** Сколько отсчётов должно продержаться у вершины, чтобы её засчитать. */
        const val MIN_TOP_SAMPLES = 2        // TUNE
        /** Ближе этого две вершины считаются одной. */
        const val MIN_GAP_MS = 60L           // TUNE

        /**
         * Вершины в последовательности ступеней.
         *
         * Основное правило прежнее: запоминаем самую высокую точку, и как
         * только сигнал от неё просел на dip ступеней — вершина состоялась.
         * Незакрытую вершину не засчитываем: пока цель ещё под катушкой,
         * счётчик иначе дёргался бы на каждом отсчёте.
         *
         * ВРЕМЯ ВЕРШИНЫ — СЕРЕДИНА ПЛАТО, А НЕ ПЕРВЫЙ ОТСЧЁТ.
         *
         * Ступеней всего восемь, поэтому на вершине сигнал стоит плато из
         * нескольких отсчётов с одинаковым значением. Брать первый из них —
         * значит систематически сдвигать цель назад по времени на всю ширину
         * плато. Середина даёт положение точнее самой сетки ступеней, и
         * промежуток между двумя целями измеряется честнее.
         *
         * ДВЕ ЗАЩИТЫ ОТ ЛОЖНЫХ ЦЕЛЕЙ.
         *
         * Одиночный выброс — скачок вверх на один отсчёт и обратно — по
         * основному правилу проходил как полноценная вершина. Теперь у вершины
         * должно набраться minTop отсчётов вблизи неё, в пределах одной
         * ступени: у выброса такой отсчёт один.
         *
         * И вершины ближе minGapMs друг к другу считаются одной: дрожание на
         * самой макушке сигнала иначе дробит одну цель на две.
         */
        fun findPeaks(s: List<Sample>, dip: Int, minTop: Int, minGapMs: Long): List<Sample> {
            if (s.size < 3) return emptyList()
            val need = maxOf(2, dip)
            val out = ArrayList<Sample>(4)

            var best = -1          // ступень кандидата
            var from = 0L          // начало плато
            var to = 0L            // конец плато
            var top = 0            // отсчётов вблизи вершины

            for (x in s) {
                if (best < 0 || x.level > best) {
                    best = x.level; from = x.t; to = x.t; top = 1
                    continue
                }
                if (x.level == best) { to = x.t; top++; continue }

                /*
                 * Просело, но меньше чем на dip — вершина ещё не закрыта.
                 *
                 * Порядок проверок здесь важен. Раньше сначала проверялось
                 * «в пределах одной ступени от вершины», и при dip = 1 та ветка
                 * забирала себе ровно тот отсчёт, который должен был вершину
                 * закрыть. С единицей в «Разделении целей» не находилось
                 * вообще ничего. Теперь первым спрашиваем про dip.
                 */
                if (best - x.level < dip) {
                    if (x.level >= best - 1) top++
                    continue
                }

                // Просело на dip и больше — вершина состоялась.
                val mid = from + (to - from) / 2
                /*
                 * Промежуток меряем от ПОСЛЕДНЕЙ найденной вершины, а не от
                 * переменной с начальным Long.MIN_VALUE.
                 *
                 * Именно на этом счётчик и встал намертво: разность
                 * mid - Long.MIN_VALUE переполняет Long и становится
                 * отрицательной, проверка на минимальный промежуток не
                 * проходила никогда, первая вершина не записывалась, а раз она
                 * не записывалась — не обновлялась и переменная. Круг замкнут,
                 * и «целей» всегда ноль. Пустой список такой ошибки не даёт.
                 */
                if (best >= need && top >= minTop &&
                    (out.isEmpty() || mid - out.last().t >= minGapMs)
                ) {
                    out += Sample(mid, best)
                }
                best = -1; top = 0
            }
            return out
        }
    }
}
