package com.alijon.detector

import android.os.SystemClock
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import kotlin.math.abs

/* ===========================================================================
 *  Проводка: отсчёты, сглаживание и поиск целей
 * ===========================================================================
 *
 *  ЗАЧЕМ ЭТО ПОЯВИЛОСЬ.
 *
 *  Задача — увидеть, что под катушкой не один предмет, а два, лежащих в
 *  десятке сантиметров друг от друга. При проводке метр в секунду это два
 *  всплеска с промежутком около сотни миллисекунд.
 *
 *  Отсчёты копятся ПО ПРИХОДУ строк. Прибор шлёт строку при каждом изменении
 *  ступени, не чаще раза в 15 мс, и с собственной меткой времени — поэтому
 *  моменты переходов известны с разрешением 15..25 мс, без дрожи эфира.
 *
 *  ЧЕГО ЭТО НЕ МОЖЕТ. Провал должен быть в самом сигнале. Восемь компараторных
 *  порогов — сетка грубая: если между целями отклик просел, но не пересёк ни
 *  одного порога, для прибора провала не было, и достать его неоткуда.
 *
 *  --- ЧТО ЗДЕСЬ ПЕРЕДЕЛАНО И ПОЧЕМУ -----------------------------------------
 *
 *  Первая редакция искала вершины заново по всему окну при каждом пришедшем
 *  отсчёте. Из-за этого вершина жила ровно столько, сколько в окне лежал её
 *  левый склон: при промежутке между целями 1,2 с и окне в секунду вторая цель
 *  вообще не встречалась с первой, а при полутора секундах первая уезжала за
 *  край сразу после того, как находилась вторая. Работал только самый длинный
 *  размах — и работал случайно.
 *
 *  Теперь вершина находится ОДИН РАЗ, в тот момент когда она случилась, и
 *  ложится в свой список со своим сроком жизни. Край окна отсчётов на счёт
 *  больше не влияет вообще, а «сколько времени видно» и «сколько держится
 *  цифра» стали двумя независимыми числами.
 *
 *  Вторая беда: «глубина провала» делала две работы сразу — глушила дрожание
 *  и задавала разделение. Поэтому и приходилось ставить тройку: не потому что
 *  цели разнесены на три ступени, а чтобы пережить дрожание на одну. Дрожание
 *  теперь снимается гистерезисом ДО поиска вершин, и провал значит ровно то,
 *  что написано на кнопке.
 */

/** Один отсчёт: когда пришёл и какая была ступень. */
data class Sample(val t: Long, val level: Int)

/**
 * Скользящее окно отсчётов, сглаживание и найденные цели.
 *
 * Пополняется из потока Bluetooth, читается с главного потока при отрисовке.
 * Списки заменяются целиком, а не правятся на месте: тот экземпляр, который
 * начал рисовать холст, уже никогда не изменится, и гонки не возникает в
 * принципе.
 */
class SweepBuffer {

    // --- настраиваемое -------------------------------------------------------

    /** Сколько времени видно на поле. Ставится из настройки «Размах». */
    var viewMs: Long = VIEW_FAST
        set(v) { field = v.coerceIn(500L, 8000L) }

    /** Сколько держится найденная цель, прежде чем счётчик её забудет. */
    var holdMs: Long = HOLD_FAST
        set(v) { field = v.coerceIn(300L, 6000L) }

    /** На сколько ступеней должен просесть сигнал между целями. */
    var dip: Int = DIP_DEFAULT

    // --- то, что читает экран ------------------------------------------------

    /*
     * Отсчёты и вершины НЕ состояние Compose, а обычные поля.
     *
     * Иначе каждая пришедшая строка — а их до шестидесяти в секунду —
     * перерисовывала бы поле целиком: полторы-две сотни кружков с
     * прозрачностью плюс ореолы плюс подписи осей. Именно это и тормозило при
     * длинном размахе.
     *
     * Вместо этого холст подписан на tick, который растёт не чаще REDRAW_MS.
     * Данные он читает уже отсюда, напрямую.
     */
    @Volatile var samples: List<Sample> = emptyList()
        private set

    @Volatile var peaks: List<Sample> = emptyList()
        private set

    /** Счётчик кадров: холст подписан на него, растёт не чаще REDRAW_MS. */
    var tick by mutableStateOf(0)
        private set

    /** Сколько целей сейчас в памяти. Меняется редко, читается подписью. */
    var count by mutableStateOf(0)
        private set

    // --- внутреннее ----------------------------------------------------------

    private var lastDeviceMs = Long.MIN_VALUE
    private var lastTickMs = 0L

    // гистерезис
    private var shown = 0
    private var pending = -1
    private var pendingSince = 0L

    // состояние поиска вершин, живёт между вызовами
    private var best = -1
    private var from = 0L
    private var to = 0L
    private var top = 0

    /**
     * @param level     ступень из телеметрии
     * @param deviceMs  собственное время прибора; null — прошивка старая,
     *                  тогда время ставит телефон.
     */
    fun add(level: Int, deviceMs: Long? = null) {
        val now: Long
        if (deviceMs != null) {
            // millis() на приборе переполняется раз в 49 суток. Прыжок назад
            // означает именно это, и старое окно после него бессмысленно.
            if (deviceMs < lastDeviceMs) clear()
            lastDeviceMs = deviceMs
            now = deviceMs
        } else {
            now = SystemClock.elapsedRealtime()
        }

        val lv = smooth(level, now)
        val point = Sample(now, lv)

        // Отсчёты: отрезаем всё, что старше окна показа, и дописываем свежий.
        val cut = now - viewMs
        var head = 0
        while (head < samples.size && samples[head].t < cut) head++
        val next = ArrayList<Sample>(samples.size - head + 1)
        for (i in head until samples.size) next.add(samples[i])
        next.add(point)
        samples = next

        stepPeak(point)
        prunePeaks(now)

        if (peaks.size != count) count = peaks.size
        if (now - lastTickMs >= REDRAW_MS) { lastTickMs = now; tick++ }
    }

    /** Связь оборвалась или прибор сменили — старое окно больше не про него. */
    fun clear() {
        samples = emptyList()
        peaks = emptyList()
        count = 0
        lastDeviceMs = Long.MIN_VALUE
        shown = 0; pending = -1
        best = -1; top = 0
        tick++
    }

    /**
     * Гистерезис: снять дрожание на одну ступень, не задержав настоящий отклик.
     *
     * У порога компаратор дребезжит — шум перебрасывает его туда-сюда, и
     * ступень скачет на единицу по нескольку раз за десятые доли секунды. Для
     * поиска вершин это яд: каждое такое дрожание закрывало кандидата, вершина
     * рассыпалась на огрызки, и проверка «минимум два отсчёта у вершины» их
     * отбрасывала. На проверке с дрожащей макушкой при глубине провала в одну
     * ступень не находилось НИ ОДНОЙ цели вместо одной настоящей.
     *
     * Правило простое и несимметричное. Скачок на две ступени и больше — это
     * настоящее движение сигнала, принимаем сразу, без задержки. Изменение на
     * одну ступень — подозрительно, ждём, удержится ли оно SETTLE_MS. Дрожание
     * столько не живёт, а настоящий медленный подъём живёт.
     */
    private fun smooth(raw: Int, now: Long): Int {
        if (raw == shown) { pending = -1; return shown }
        if (abs(raw - shown) >= SETTLE_JUMP) { shown = raw; pending = -1; return shown }
        if (pending != raw) { pending = raw; pendingSince = now }
        if (now - pendingSince >= SETTLE_MS) { shown = raw; pending = -1 }
        return shown
    }

    /**
     * Один шаг поиска вершины. Состояние живёт между вызовами, поэтому вершина
     * находится один раз и от длины окна отсчётов не зависит.
     *
     * Время вершины — СЕРЕДИНА ПЛАТО. Ступеней всего восемь, на макушке сигнал
     * стоит плато из нескольких отсчётов, и брать первый из них значит
     * систематически сдвигать цель назад по времени на всю ширину плато.
     */
    private fun stepPeak(x: Sample) {
        if (best < 0 || x.level > best) {
            best = x.level; from = x.t; to = x.t; top = 1
            return
        }
        if (x.level == best) { to = x.t; top++; return }

        // Просело, но меньше чем на dip — вершина ещё не закрыта. Про dip
        // спрашиваем ПЕРВЫМ: иначе при dip = 1 ветка «в пределах одной ступени»
        // забирала себе тот самый отсчёт, который должен вершину закрыть.
        if (best - x.level < dip) {
            if (x.level >= best - 1) top++
            return
        }

        val mid = from + (to - from) / 2
        val last = peaks.lastOrNull()
        if (best >= maxOf(2, dip) && top >= MIN_TOP_SAMPLES &&
            (last == null || mid - last.t >= MIN_GAP_MS)
        ) {
            peaks = peaks + Sample(mid, best)
        }
        best = -1; top = 0
    }

    /** Забыть цели старше срока удержания. */
    private fun prunePeaks(now: Long) {
        val cut = now - holdMs
        if (peaks.isEmpty() || peaks.first().t >= cut) return
        peaks = peaks.filter { it.t >= cut }
    }

    companion object {
        /*
         * Три размаха. Показ всегда длиннее удержания — чтобы каждая
         * посчитанная цель была ещё и видна на поле: цифра и картинка не должны
         * противоречить друг другу.
         */
        const val VIEW_FAST = 1600L; const val HOLD_FAST = 1000L   // TUNE
        const val VIEW_MID  = 2400L; const val HOLD_MID  = 1500L   // TUNE
        const val VIEW_SLOW = 4000L; const val HOLD_SLOW = 2500L   // TUNE

        /** 0 — быстро, 1 — средне, 2 — медленно. Так хранится настройка. */
        fun viewFor(speed: Int): Long = when (speed) {
            2 -> VIEW_SLOW; 1 -> VIEW_MID; else -> VIEW_FAST
        }
        fun holdFor(speed: Int): Long = when (speed) {
            2 -> HOLD_SLOW; 1 -> HOLD_MID; else -> HOLD_FAST
        }

        const val DIP_DEFAULT = 2            // TUNE: провал между целями, ступеней

        /** Гистерезис: скачок от скольких ступеней принимается сразу. */
        const val SETTLE_JUMP = 2            // TUNE
        /** Сколько должно продержаться изменение на одну ступень. */
        const val SETTLE_MS = 40L            // TUNE

        /** Сколько отсчётов должно продержаться у вершины, чтобы её засчитать. */
        const val MIN_TOP_SAMPLES = 2        // TUNE
        /** Ближе этого две вершины считаются одной. */
        const val MIN_GAP_MS = 60L           // TUNE

        /** Не чаще этого перерисовывается поле. 33 мс — тридцать кадров в секунду. */
        const val REDRAW_MS = 33L            // TUNE
    }
}
